void solve() {
    int n;
    cin>>n;
    vi a(n);
    ll sum = 0;
    ll mx = LLONG_MIN;
    for(int i=0; i<n; i++){
        cin>>a[i];
        sum += a[i];
        if(sum < 0){
            sum = 0;
        }
        mx = max(mx,sum);
    }
    if(mx==0) mx = *max_element(all(a));
    cout<<mx<<endl;
}

