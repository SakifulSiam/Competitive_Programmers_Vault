void solve() {
    string s;
    cin>>s;
    int n = s.length();
    int barbe = 0,kombe = 0;
    for(int i=1; i<n-1; i++){
        if(s[i-1]==s[i+1]){
            if(s[i]==s[i-1])barbe=1;
            else kombe = 1;
        }
    }
    cout<<1+barbe+kombe<<endl;
}

